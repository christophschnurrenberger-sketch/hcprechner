const CATALOG: Record<GpsLocale, Record<GpsMessageKey, string>> = { de, en };

/** Sprache der Oberfläche (html lang), Standard Deutsch. */
export function gpsLocale(): GpsLocale {
  if (typeof document !== "undefined" && document.documentElement.lang?.toLowerCase().startsWith("en")) return "en";
  return "de";
}

export function gpsText(key: GpsMessageKey, params: Record<string, string | number> = {}, locale: GpsLocale = gpsLocale()): string {
  const template = CATALOG[locale][key] ?? de[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => (name in params ? String(params[name]) : `{${name}}`));
}

/** Zahl in der Schreibweise der Sprache (z. B. 1.500). */
export function formatGpsNumber(value: number, locale: GpsLocale = gpsLocale()): string {
  return new Intl.NumberFormat(locale === "en" ? "en-GB" : "de-DE", { maximumFractionDigits: 0 }).format(value);
}
